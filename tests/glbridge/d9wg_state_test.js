"use strict";
const assert = require("node:assert/strict");
const S = require("../../src/browser/glbridge/d3d9-webgpu/d9wg_state.js");
const { makeExecutor } = require("./d3d9_webgpu_executor_test.js");
(async () => {
    const { executor, fake } = makeExecutor();
    await executor.initialize();
    const a = executor.createDeviceState(1), b = executor.createDeviceState(2);
    a.vsConstF[3] = 7;a.psConstF[1] = 9;a.transforms.set(99, [1]);a.clipPlanes[0][0] = 42;
    assert.equal(b.vsConstF[3], 0);assert.equal(b.psConstF[1], 0);
    assert.equal(b.transforms.has(99), false);assert.equal(b.clipPlanes[0][0], 0);
    const alive = [true, true], buffers = alive.map((_, i) => ({ destroy() { alive[i] = false; } }));
    executor.switchSession("0000000000000001");
    executor.uniformRingChunks.push(buffers[0]);executor.uniformStaging.push(new Uint8Array([11]));
    executor.uniformRingCursor = 512;
    executor.sessionStates.get(executor.sessionKey).featureBits = 123;
    executor.switchSession("0000000000000002");
    executor.uniformRingChunks.push(buffers[1]);executor.uniformStaging.push(new Uint8Array([22]));
    executor.uniformRingCursor = 256;
    executor.switchSession("0000000000000001");
    assert.equal(executor.uniformRingCursor, 512);assert.equal(executor.uniformStaging[0][0], 11);
    assert.equal(executor.sessionStates.get(executor.sessionKey).featureBits, 123);
    executor.releaseActiveSession("test-owner-release");
    fake.completeSubmittedWork();await Promise.resolve();
    assert.deepEqual(alive, [false, true], "ending A must retire only A's GPU storage");
    executor.switchSession("0000000000000002");
    assert.equal(executor.uniformRingCursor, 256);assert.equal(executor.uniformStaging[0][0], 22);
    executor.releaseActiveSession("test-owner-release");
    fake.completeSubmittedWork();await Promise.resolve();assert.deepEqual(alive, [false, false]);
    assert.equal(S.SESSION_FIELDS.includes("uniformRingCursor"), true);
    console.log("D9WG state: isolated device registers, pending session constants and owner GPU retirement checked");
})().catch(error => { console.error(error);process.exitCode = 1; });

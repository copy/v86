#!/usr/bin/env node
// The decoders' catalogue of encodings (src/rust/decode/encodings.rs), from
// x86_table only. (gen/generate_ir_decoder.js until docs/jit-unification-plan.md
// M11 deleted the IR region tiers, whose coverage of each form it also wrote.)
import fs from "node:fs";
import assert from "node:assert/strict";
import table, {opcode_map, opcode_prefix, opcode_family as family_key, mmx_form} from "./x86_table.js";
const hex = n => n.toString(16).toUpperCase();
const family_modrm = new Map();
for(const e of table) if(!e.escape && !family_modrm.has(family_key(e.opcode))) family_modrm.set(family_key(e.opcode), !!e.e);
// (escapes: the decoders read the third opcode byte of 0F 38 and 0F 3A)
const source_rows = table.filter(e => !e.prefix && !e.escape);
// The interpreter group switch delivers #UD immediately for absent /g entries:
// ModRM has been fetched, but EA/immediate/task guards have not run.
const grouped = new Map();
// (a VEX encoding that no row accepts is #UD: decode_rules::vex_row)
for(const e of source_rows) if(e.fixed_g !== undefined && !e.vex) {
    if(!grouped.has(e.opcode)) grouped.set(e.opcode, new Set());
    grouped.get(e.opcode).add(e.fixed_g);
}
for(const [opcode, groups] of grouped) for(let fixed_g=0; fixed_g<8; fixed_g++) {
    if(!groups.has(fixed_g)) source_rows.push({opcode, fixed_g, group_ud:true, reg_ud:true, mem_ud:true, custom:true, block_boundary:true, no_next_instruction:true});
}
// Ids: key * 16 + group slot; the three-byte maps (whose keys are too wide
// for that) above 0x10000000, by map, prefix and opcode byte; VEX rows above
// 0x20000000, by map, pp, opcode byte and their order in the key
const vex_ordinal = new Map();
for(const e of source_rows) if(e.vex) {
    const rows = vex_ordinal.get(e.opcode) || [];
    vex_ordinal.set(e.opcode, rows);
    rows.push(e);
    assert.ok(rows.length <= 16);
}
const encoding_id = e => {
    const slot = e.fixed_g === undefined ? 0 : e.fixed_g + 1;
    const map = opcode_map(e.opcode);
    if(e.vex) {
        const vex_map = e.opcode >>> 16 & 0xFF, pp = e.opcode >>> 8 & 0xFF;
        return 0x20000000 + (((vex_map - 1) * 4 + pp) * 256 + (e.opcode & 0xFF)) * 16 + vex_ordinal.get(e.opcode).indexOf(e);
    }
    if(map !== "0F38" && map !== "0F3A") return e.opcode * 16 + slot;
    const prefix = {0: 0, 0x66: 1, 0xF2: 2, 0xF3: 3}[opcode_prefix(e.opcode)];
    return 0x10000000 + (((map === "0F3A") * 4 + prefix) * 256 + (e.opcode & 0xFF)) * 16 + slot;
};
// (sorted by key: the decoders binary-search the catalogue)
const rows = source_rows.filter(e => !e.prefix).map(e => ({...e,
    id: encoding_id(e),
    fetch_modrm: family_modrm.get(family_key(e.opcode)),
    mmx: e.sse && mmx_form(e.opcode),
})).sort((a, b) => a.opcode - b.opcode || (a.fixed_g ?? -1) - (b.fixed_g ?? -1));
assert.equal(new Set(rows.map(e => e.id)).size, rows.length);
const bool = x => x ? "true" : "false";
const imm = e => e.imm8 ? "Byte" : e.imm8s ? "SignedByte" : e.imm16 ? "Word" :
    e.imm1632 ? "Operand" : e.immaddr ? "Address" : "None";
const flags = ["fetch_modrm", "group_ud", "task_switch_test", "custom", "e", "ignore_mod", "reg_ud", "mem_ud", "os", "block_boundary", "no_next_instruction",
    "absolute_jump", "jump_offset_imm", "conditional_jump", "custom_sti", "is_fpu", "sse", "mmx", "is_string", "unimplemented"];
const refining = e => e.sse || e.refining === 1 ? "crate::decode_rules::REFINING_ALL" : e.refining === "rep" ? "crate::decode_rules::REFINING_REP" : "0";
const feature = e => e.feature ? "crate::cpu::features::" + e.feature.replace(".", "_") : "0";
// the VEX fields a VEX row accepts (gen/vex_table.js, decode_rules::vex)
const vex_rule = e => {
    if(!e.vex) return "0";
    const v = e.vex;
    return ["ROW", v.l === 0 && "L0", v.l === 1 && "L1", v.w === 0 && "W0", v.w === 1 && "W1", v.wig32 && "WIG32", v.vvvv && "VVVV",
        v.long && "LONG", v.is4 && "IS4", v.vsib && "VSIB", v.unique && "UNIQUE", v.gpr && "GPR"].filter(Boolean).map(b => "vex::" + b).join(" | ");
};
let rust = "// Generated by gen/generate_decoder.js. Do not edit.\nuse super::{Encoding, ImmediateKind};\nuse crate::decode_rules::vex;\n#[rustfmt::skip]\npub static ENCODINGS: &[Encoding] = &[\n";
for(const e of rows) {
    rust += `    Encoding { id: ${e.id}, opcode: 0x${hex(e.opcode)}, group: ${e.fixed_g ?? -1}, immediate: ImmediateKind::${imm(e)}, extra_bytes: ${e.extra_imm16 ? 2 : e.extra_imm8 ? 1 : 0}, refining: ${refining(e)}, feature: ${feature(e)}, vex: ${vex_rule(e)}, ${flags.map(k => `${k}: ${bool(e[k])}`).join(", ")} },\n`;
}
rust += "];\n";
// Bounded binary search over a generated opcode-key index, followed by <= 8 group entries.
const buckets = new Map();
for(let i = 0; i < rows.length; i++) {
    const opcode = rows[i].opcode;
    if(!buckets.has(opcode)) buckets.set(opcode, [i, i]);
    buckets.get(opcode)[1] = i + 1;
}
rust += "pub static OPCODES: &[(u32, usize, usize)] = &[\n";
for(const [opcode, [start, end]] of buckets) rust += `    (0x${hex(opcode)}, ${start}, ${end}),\n`;
rust += "];\n";
// The iced-x86 form (gen/isa_forms.json) of each VEX row, for tests
rust += "#[cfg(test)]\npub static FORMS: &[(u32, &str)] = &[\n";
for(const e of [...rows].filter(e => e.form).sort((a, b) => a.id - b.id)) rust += `    (${e.id}, "${e.form}"),\n`;
rust += "];\n";
const outputs = [["src/rust/decode/encodings.rs", rust]];
for(const [path, content] of outputs) {
    if(process.argv.includes("--check")) assert.equal(fs.readFileSync(path, "utf8"), content, `${path} is stale`);
    else fs.writeFileSync(path, content);
}
console.log(`decoder catalogue: ${rows.length} encodings`);

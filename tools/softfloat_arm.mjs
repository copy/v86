#!/usr/bin/env node
// The ARM core's SoftFloat (docs/arm64-virt-android16-plan.md P2.6):
// lib/softfloat/softfloat.c is SoftFloat 3e with the 8086-SSE
// specialization; this writes it with the ARM-VFPv2 one instead (the
// differences of source/ARM-VFPv2 in the SoftFloat 3e distribution):
// tininess before rounding, positive default NaNs, a signaling NaN of
// either operand propagates (A before B), and integer conversions of a NaN
// give 0 and saturate an overflow to the type's limit. The ARM core links
// only this one, so no symbol needs a prefix.
//
//   node tools/softfloat_arm.mjs lib/softfloat/softfloat.c build/softfloat_arm.c
import assert from "node:assert/strict";
import fs from "node:fs";

const [input, output] = process.argv.slice(2);
let s = fs.readFileSync(input, "utf8");
const replace = (from, to) => {
    const count = s.split(from).length - 1;
    assert.equal(count, 1, "expected once: " + from);
    s = s.replace(from, to);
};
replace("#define init_detectTininess softfloat_tininess_afterRounding", "#define init_detectTininess softfloat_tininess_beforeRounding");
replace("#define ui32_fromNegOverflow 0xFFFFFFFF", "#define ui32_fromNegOverflow 0");
replace("#define ui32_fromNaN         0xFFFFFFFF", "#define ui32_fromNaN         0");
replace("#define i32_fromPosOverflow  (-0x7FFFFFFF - 1)", "#define i32_fromPosOverflow  0x7FFFFFFF");
replace("#define i32_fromNaN          (-0x7FFFFFFF - 1)", "#define i32_fromNaN          0");
replace("#define ui64_fromNegOverflow UINT64_C( 0xFFFFFFFFFFFFFFFF )", "#define ui64_fromNegOverflow 0");
replace("#define ui64_fromNaN         UINT64_C( 0xFFFFFFFFFFFFFFFF )", "#define ui64_fromNaN         0");
replace("#define i64_fromPosOverflow  (-INT64_C( 0x7FFFFFFFFFFFFFFF ) - 1)", "#define i64_fromPosOverflow  INT64_C( 0x7FFFFFFFFFFFFFFF )");
replace("#define i64_fromNaN          (-INT64_C( 0x7FFFFFFFFFFFFFFF ) - 1)", "#define i64_fromNaN          0");
replace("#define defaultNaNF16UI 0xFE00", "#define defaultNaNF16UI 0x7E00");
replace("#define defaultNaNF32UI 0xFFC00000", "#define defaultNaNF32UI 0x7FC00000");
replace("#define defaultNaNF64UI UINT64_C( 0xFFF8000000000000 )", "#define defaultNaNF64UI UINT64_C( 0x7FF8000000000000 )");
// (8086-SSE: a quiet NaN in A beats a signaling NaN in B; ARM: the signaling one)
replace("        if ( isSigNaNA ) return uiA | 0x0200;", "        return (isSigNaNA ? uiA : uiB) | 0x0200;");
replace("        if ( isSigNaNA ) return uiA | 0x00400000;", "        return (isSigNaNA ? uiA : uiB) | 0x00400000;");
replace("        if ( isSigNaNA ) return uiA | UINT64_C( 0x0008000000000000 );", "        return (isSigNaNA ? uiA : uiB) | UINT64_C( 0x0008000000000000 );");
fs.writeFileSync(output, "/* generated by tools/softfloat_arm.mjs from " + input + ": the ARM-VFPv2 specialization */\n" + s);

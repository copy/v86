#!/usr/bin/env node
// Writes what is generated from src/browser/glbridge/d3d9-webgpu/d9wg_protocol.js:
//
//   node tools/gen_d9wg_header.mjs <retro-gaming-site>/glbridge/d3d9proxy/d3d9_protocol.h
//   node tools/gen_d9wg_header.mjs --svga src/graphics_adapters/vmware_svga/d9wg_constants.js
//
// The first is the guest's header: every struct gets an assert of its size and
// of every field's offset, so the C a guest DLL is built with cannot disagree
// with the layout the executor reads. The second is the constants and payload
// sizes the SVGA3D encoder (svga3d_d9wg.js) writes batches with. With no path
// it prints the header.
import { createRequire as create_require } from "node:module";
import { writeFileSync as write_file_sync } from "node:fs";

const require = create_require(import.meta.url);
const P = require("../src/browser/glbridge/d3d9-webgpu/d9wg_protocol.js");

const SCALARS = new Set(["uint8_t", "uint16_t", "uint32_t", "int32_t", "float"]);
const ctype = type => {
    const base = type.replace(/^volatile /, "");
    return (type.startsWith("volatile ") ? "volatile " : "") + (SCALARS.has(base) ? base : "D9WG" + base);
};

function render() {
    const out = ["/* Generated by v86's tools/gen_d9wg_header.mjs from",
        " * src/browser/glbridge/d3d9-webgpu/d9wg_protocol.js -- edit that, not this. */", ""];
    let asserts = false;
    for(const item of P.ITEMS) {
        if(item.raw) {
            // the asserts go in before the include guard closes
            if(!asserts && item.raw.some(line => line.startsWith("#endif"))) {
                out.push(...assertions());
                asserts = true;
            }
            out.push(...item.raw);
        } else if(item.comment) {
            out.push(...item.comment);
        } else if(item.define) {
            out.push(...item.text);
        } else if(item.opcodes) {
            out.push("enum D9WGOpcode {");
            const last = item.opcodes.filter(Array.isArray).at(-1)[0];
            for(const entry of item.opcodes) {
                if(entry.comment) out.push(...entry.comment);
                else if(entry.blank) out.push("");
                else {
                    const [name, value, note] = entry;
                    const literal = value >= 0x100 ? "0x" + value.toString(16).toUpperCase() : String(value);
                    const line = "    D9WG_OP_" + name + " = " + literal + (name === last ? "" : ",");
                    out.push(note ? (line.length < 45 ? line.padEnd(45) : line + " ") + "/* " + note + " */" : line);
                }
            }
            out.push("};");
        } else if(item.struct) {
            out.push("typedef struct D9WG" + item.struct + " {");
            for(const field of item.fields) {
                if(field.comment) { out.push(...field.comment); continue; }
                const [type, name, dims = [], note] = field;
                const line = "    " + ctype(type) + " " + name + dims.map(d => "[" + d + "]").join("") + ";";
                out.push(note ? line + " /* " + note + " */" : line);
            }
            out.push("} D9WG" + item.struct + ";" + (item.note ? " /* " + item.note + " */" : ""));
        }
    }
    if(!asserts) throw new Error("no #endif in ITEMS to put the asserts before");
    return out.join("\n");
}

function assertions() {
    const out = ["/* The layout d9wg_protocol.js describes: every struct's size and every", " * field's offset. */",
        "#include <stddef.h>", ""];
    for(const [name, struct] of Object.entries(P.STRUCTS)) {
        out.push("typedef char D9WGAssert" + name + "Size[sizeof(D9WG" + name + ") == " + struct.size + " ? 1 : -1];");
        for(const [field, layout] of Object.entries(struct.fields))
            out.push("typedef char D9WGAssert" + name + "_" + field + "[offsetof(D9WG" + name + ", " + field +
                ") == " + layout.offset + " ? 1 : -1];");
    }
    out.push("");
    return out;
}

const hex = value => "0x" + value.toString(16).toUpperCase();

function svga_module() {
    const out = ["// Generated by tools/gen_d9wg_header.mjs from",
        "// src/browser/glbridge/d3d9-webgpu/d9wg_protocol.js -- edit that, not this.",
        "// The D9WG constants the SVGA3D layer writes batches with (svga3d_d9wg.js).", "",
        "export const D9WG_MAGIC = " + hex(P.C.D9WG_MAGIC) + ";",
        "export const D9WG_VERSION_MAJOR = " + P.C.D9WG_VERSION_MAJOR + ";",
        "export const D9WG_VERSION_MINOR = " + P.C.D9WG_VERSION_MINOR + ";", "",
        "/** The batch flag that makes the executor submit the frame's GPU work */",
        "export const D9WG_BATCH_FLAG_PRESENT = " + P.C.D9WG_BATCH_FLAG_PRESENT + ";", "",
        "/** Opcodes (enum D9WGOpcode) */", "export const OP = {"];
    for(const [name, value] of Object.entries(P.OP)) out.push("    " + name + ": " + hex(value) + ",");
    out.push("};", "", "/** Resource kinds (D9WG_RESOURCE_*) */", "export const KIND = {");
    for(const [name, value] of Object.entries(P.C)) {
        if(name.startsWith("D9WG_RESOURCE_")) out.push("    " + name.slice("D9WG_RESOURCE_".length) + ": " + value + ",");
    }
    out.push("};", "", "/** Native NV render-state extensions (SetRenderState). */", "export const NV_RS = {");
    for(const [name,value] of Object.entries(P.C))
        if(name.startsWith("D9WG_NV_RS_")) out.push("    " + name.slice("D9WG_NV_RS_".length) + ": " + hex(value) + ",");
    out.push("};", "", "/** Each opcode's payload struct, in bytes: a command's payload is at least this long */",
        "export const PAYLOAD_BYTES = {");
    for(const name of Object.keys(P.COMMANDS)) {
        out.push("    [OP." + name + "]: " + P.STRUCTS[P.commandStruct(P.OP[name])].size + ",");
    }
    out.push("};", "");
    out.push("/** Named payload layouts: [field, offset, scalar type, count]. */", "export const FIELD_LAYOUT = {");
    for(const [name, struct] of Object.entries(P.STRUCTS)) {
        out.push("    " + JSON.stringify(name) + ": { bytes: " + struct.size + ", fields: [");
        for(const [field, layout] of Object.entries(struct.fields))
            out.push("        " + JSON.stringify([field, layout.offset, layout.type, layout.count]) + ",");
        out.push("    ] },");
    }
    out.push("};", "", "export const COMMAND_STRUCT = {");
    for(const name of Object.keys(P.COMMANDS))
        out.push("    [OP." + name + "]: " + JSON.stringify(P.commandStruct(P.OP[name])) + ",");
    out.push("};", "");
    return out.join("\n");
}

const args = process.argv.slice(2);
const svga = args.indexOf("--svga");
if(svga >= 0) {
    write_file_sync(args[svga + 1], svga_module());
    args.splice(svga, 2);
}
if(args[0]) write_file_sync(args[0], render());
else if(svga < 0) process.stdout.write(render());

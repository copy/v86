#!/usr/bin/env node
// SDK-free C layout facts from the host's canonical storage table.
import assert from "node:assert/strict";
import fs from "node:fs";
import {createRequire as create_require} from "node:module";
const require = create_require(import.meta.url), {FORMAT_LAYOUT_ROWS: rows} = require("../src/browser/glbridge/d3d9-webgpu/d9wg_formats.js");
const ids = new Set();
for (const [format, width, height, bytes, apis, depth] of rows) {
    assert(Number.isInteger(format) && format >= 0 && format <= 0xffffffff && !ids.has(format)); ids.add(format);
    assert([1, 2, 4].includes(width) && [1, 4].includes(height) && [1, 2, 3, 4, 8, 16].includes(bytes));
    assert(Number.isInteger(apis) && apis >= 0 && apis <= 7 && [0, 1].includes(depth));
}
const lines = ["/* Generated by v86 tools/gen_d9wg_format_layouts.mjs from d9wg_formats.js. */", "#ifndef D9WG_FORMAT_LAYOUTS_H", "#define D9WG_FORMAT_LAYOUTS_H", "#include <stdint.h>",
    "typedef struct D9WGFormatLayout {", "    uint32_t format;", "    uint8_t block_width, block_height, block_bytes, apis, depth;", "} D9WGFormatLayout;", "static const D9WGFormatLayout d9wg_format_layouts[] = {"];
for (const row of rows) lines.push("    {" + row.map(n => n + "u").join(", ") + "},");
lines.push("};", "static __inline const D9WGFormatLayout *d9wg_find_format(uint32_t format)", "{", "    switch (format) {");
rows.forEach((row, i) => lines.push("    case " + row[0] + "u: return d9wg_format_layouts + " + i + "u;"));
lines.push("    default: return 0;", "    }", "}",
    "static __inline int d9wg_format_layout(uint32_t api, uint32_t format,", "        uint32_t *width, uint32_t *height, uint32_t *bytes)", "{",
    "    const D9WGFormatLayout *layout = d9wg_find_format(format);",
    "    if (!layout || api < 7u || api > 9u || !(layout->apis & (1u << (api - 7u))) || !width || !height || !bytes) return 0;",
    "    *width = layout->block_width;*height = layout->block_height;*bytes = layout->block_bytes;return 1;", "}",
    "static __inline int d9wg_texture_level_layout(uint32_t api, uint32_t format, uint32_t width, uint32_t height,",
    "        uint32_t *row_pitch, uint32_t *row_count, uint32_t *byte_count)", "{",
    "    uint32_t bw, bh, bytes, columns, rows, pitch;",
    "    if (!row_pitch || !row_count || !byte_count || !d9wg_format_layout(api, format, &bw, &bh, &bytes)) return 0;",
    "    /* Quotient plus remainder cannot overflow at UINT32_MAX. */",
    "    columns = width / bw + (width % bw != 0u);rows = height / bh + (height % bh != 0u);",
    "    if (columns > 0xffffffffu / bytes) return 0;",
    "    pitch = columns * bytes;",
    "    if (rows && pitch > 0xffffffffu / rows) return 0;",
    "    *row_pitch = pitch;*row_count = rows;*byte_count = pitch * rows;return 1;", "}", "#endif", "");
const text = lines.join("\n"), args = process.argv.slice(2), check = args[0] === "--check", file = args[check ? 1 : 0];
if (check) { assert(file, "--check requires a header path"); assert.equal(fs.readFileSync(file, "utf8"), text, "format layout header drift"); console.log("PASS generated format layouts match canonical host table"); }
else if (file) fs.writeFileSync(file, text); else process.stdout.write(text);

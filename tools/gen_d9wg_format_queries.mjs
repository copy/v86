#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import {createRequire as create_require} from "node:module";
const require = create_require(import.meta.url), F = require("../src/browser/glbridge/d3d9-webgpu/d9wg_formats.js"), ids = new Set();
const lines = ["/* Generated by v86 tools/gen_d9wg_format_queries.mjs from d9wg_formats.js. */", "#ifndef D9WG_FORMAT_QUERIES_H", "#define D9WG_FORMAT_QUERIES_H", "#include <stdint.h>"];
for (const [name, value] of Object.entries(F.FORMAT_QUERY)) lines.push("#define D9WG_FORMAT_QUERY_" + name + " 0x" + value.toString(16).toUpperCase() + "u");
lines.push("static __inline uint32_t d9wg_format_query_info(uint32_t format)", "{", "    switch (format) {");
for (const [format, flags] of F.FORMAT_QUERY_ROWS) { assert(!ids.has(format) && Number.isInteger(format) && format >= 0 && format <= 0xffffffff && flags > 0 && flags < 64); ids.add(format); lines.push("    case " + format + "u: return " + flags + "u;"); }
lines.push("    default: return 0;", "    }", "}",
    "static __inline int d9wg_format_query_supported(uint32_t type, uint32_t usage, uint32_t format,",
    "        uint32_t host_features, uint32_t shader_model, int renderable)", "{",
    "    if (usage & 0x10u) return 0; /* No programmable CPU vertex texture execution yet. */",
    "    uint32_t info = d9wg_format_query_info(format);",
    "    if ((info & 32u) && !(host_features & 4u)) return 0; /* No CPU BC fallback. */",
    "    uint32_t query = usage & D9WG_FORMAT_QUERY_MASK;",
    "    if (!query) return 1;",
    "    int texture = type == 3u || type == 4u || type == 5u;",
    "    int target = renderable && (type == 1u || type == 3u || type == 5u);",
    "    if (!info || (query & D9WG_FORMAT_QUERY_LEGACYBUMPMAP)) return 0;",
    "    if ((query & D9WG_FORMAT_QUERY_FILTER) && (!texture || !(info & 1u) || ((info & 8u) && !(info & 16u)) || ((info & 4u) && !(host_features & 1u)))) return 0;",
    "    if ((query & D9WG_FORMAT_QUERY_SRGBREAD) && (!texture || !(info & 2u))) return 0;",
    "    if ((query & D9WG_FORMAT_QUERY_SRGBWRITE) && (!target || !(info & 2u))) return 0;",
    "    if ((query & D9WG_FORMAT_QUERY_BLENDING) && (!target || (info & 8u) || ((info & 4u) && !(host_features & 2u)))) return 0;",
    "    if ((query & D9WG_FORMAT_QUERY_VERTEXTEXTURE) && (type != 3u || shader_model < 3u || (info & 8u))) return 0;",
    "    if ((query & D9WG_FORMAT_QUERY_WRAPANDMIP) && (!texture || (info & 8u))) return 0;",
    "    return 1;", "}", "#endif", "");
const text = lines.join("\n"), args = process.argv.slice(2), check = args[0] === "--check", file = args[check ? 1 : 0];
if (check) { assert(file); assert.equal(fs.readFileSync(file, "utf8"), text, "format query header drift"); console.log("PASS generated format query header matches canonical host facts"); }
else if (file) fs.writeFileSync(file, text); else process.stdout.write(text);
